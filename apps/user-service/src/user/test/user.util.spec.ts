import {isAdult} from '../user.util.js';

describe('[CASES:isAdult] 성인 — 청소년보호법: 한국 날짜의 올해 − 출생 연도 ≥ 19 (생일은 보지 않는다)', () => {
    it.each([
        ['2026-10-22T03:00:00.000Z', '2007-12-31', true, '① 그해 19세 — 생일 전이어도 성인'],
        ['2026-10-22T03:00:00.000Z', '2008-01-01', false, '② 그해 18세 — 미성년'],
        ['2026-10-22T03:00:00.000Z', '2007-01-01', true, '③ 그해 19세'],
        ['2026-10-22T03:00:00.000Z', '1970-01-01', true, '④ 한참 지난 성인'],
        ['2026-12-31T15:00:00.000Z', '2008-06-01', true, '⑤ 한국 2027-01-01 00:00 — 한국 날짜로 새해라 19세'],
        ['2026-12-31T14:59:59.000Z', '2008-06-01', false, '⑥ 한국 2026-12-31 23:59:59 — 아직 18세'],
    ])('now %s · birth %s → %s (%s)', (now, birth, expected) => {
        expect(isAdult(birth, new Date(now))).toBe(expected);
    });
});
